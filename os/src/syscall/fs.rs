/// eventfd2 syscall (ID = 290)
///
/// C interface: `int eventfd(unsigned int initval, int flags)`
///
/// `flags` may be 0 or any bitwise-or of:
/// * `EFD_SEMAPHORE` (1): read returns 1 and decrements the counter;
/// * `EFD_NONBLOCK`  (2048): failed read/write returns -2 instead of blocking.
///
/// Returns the new fd on success, -1 when the flags are invalid or the
/// process' file descriptor table has reached its limit.
pub fn sys_eventfd2(initval: u32, flags: i32) -> isize {
    trace!(
        "kernel:pid[{}] sys_eventfd2 initval={} flags={:#x}",
        current_task().unwrap().process.upgrade().unwrap().getpid(),
        initval,
        flags
    );
    // Validate flags first: create_eventfd returns None for unknown bits.
    if let Some(eventfd) = create_eventfd(initval, flags) {
        let process = current_process();
        let mut inner = process.inner_exclusive_access();
        // Enforce the per-process descriptor limit, but reuse a free slot if
        // one exists below the limit.
        if inner.fd_table_full() {
            return -1;
        }
        let fd = inner.alloc_fd();
        inner.fd_table[fd] = Some(eventfd);
        return fd as isize;
    }
    -1
}

/// Legacy `eventfd` syscall (ID = 284).  It is identical to
/// `sys_eventfd2(initval, 0)` because it cannot carry a flags argument.
pub fn sys_eventfd(initval: u32) -> isize {
    sys_eventfd2(initval, 0)
}
